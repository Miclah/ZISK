    /// <summary>
    /// Looks up a key's text for the given language. Returns the key itself (never throws) if
    /// the key is missing - that makes a missed translation loudly visible in the UI during
    /// development instead of silently rendering blank.
    /// </summary>
    public static string Get(Lang lang, string key)
    {
        if (!Entries.TryGetValue(key, out var pair))
            return key;

        return lang == Lang.En ? pair.En : pair.Sk;
    }
